open! Alice_stdlib
open Alice_hierarchy
open Alice_package
open Alice_ocaml_toolchain
open Dependency_graph
module Package_base_dir = Build_dir.Package_base_dir

let basename = Basename.of_filename ".merlin"

let header_comment =
  {|# Generated by Alice.
# This file is necessary for LSP to work in Alice projects.
# It will be automatically updated when the project is built.
# Don't check this file into version control.
# See https://www.alicecaml.org/lsp for more info.
|}
;;

let dot_merlin_text_initial () =
  let source_rel_path = Relative_path.of_basename Alice_package.Package.src in
  sprintf "%s\nS %s" header_comment (Relative_path.to_filename source_rel_path)
;;

let dot_merlin_text
      package_with_deps
      build_dir
      (build_config : Build_config.t)
      ~config_script_dependency_graph
  =
  let get_package_base_dir dep =
    let dep_id = Package_with_deps.id dep in
    Build_dir.package_base_dir_of_build_config build_dir dep_id build_config
  in
  let build_abs_paths_for_deps =
    Package_with_deps.immediate_deps_in_dependency_order package_with_deps
    |> List.concat_map ~f:(fun dep ->
      let package_base_dir = get_package_base_dir dep in
      [ Package_base_dir.public_dir package_base_dir
      ; Package_base_dir.public_for_lsp_dir package_base_dir
      ])
  in
  let build_abs_paths_for_config_script_deps =
    Dependency_graph.roots config_script_dependency_graph
    |> List.concat_map ~f:(fun dep ->
      let dep_id = Package_with_deps.id dep in
      let build_config = Build_config.for_config_script build_config in
      let package_base_dir =
        Build_dir.package_base_dir_of_build_config build_dir dep_id build_config
      in
      [ Package_base_dir.public_dir package_base_dir
      ; Package_base_dir.public_for_lsp_dir package_base_dir
      ])
  in
  let package_base_dir = get_package_base_dir package_with_deps in
  let build_abs_paths =
    Package_base_dir.private_dir package_base_dir
    :: (build_abs_paths_for_deps @ build_abs_paths_for_config_script_deps)
  in
  let to_relative_paths ~prefix =
    List.map build_abs_paths ~f:(Absolute_path.chop_prefix ~prefix)
  in
  let build_rel_paths =
    match Package_with_deps.package package_with_deps |> Alice_package.Package.root with
    | `Root prefix -> to_relative_paths ~prefix
    | `Non_root prefix -> to_relative_paths ~prefix
  in
  let source_rel_path = Relative_path.of_basename Alice_package.Package.src in
  let ocamllib_path_line =
    let ocamllib_path = Ocaml_toolchain.standard_library build_config.ocaml_toolchain in
    (* It's probably more correct to specify the OCaml library path with
       "FLG -ocamllib-path" however this doesn't seem to work on Windows, so
       just use a "B" directive instead. *)
    sprintf "B %s" (Absolute_path.to_filename ocamllib_path)
  in
  let builtin_modules_lines =
    Package_with_deps.builtin_modules package_with_deps
    |> Builtin_module.Set.to_list
    |> List.map ~f:(fun builtin_module ->
      sprintf
        "B %s"
        (Ocaml_toolchain.builtin_module_dir build_config.ocaml_toolchain builtin_module
         |> Absolute_path.to_filename))
  in
  let lines =
    List.concat
      [ [ sprintf "S %s" (Relative_path.to_filename source_rel_path) ]
      ; [ ocamllib_path_line ]
      ; builtin_modules_lines
      ; List.map build_rel_paths ~f:(fun build_rel_path ->
          sprintf "B %s" (Relative_path.to_filename build_rel_path))
      ]
  in
  let text = String.concat lines ~sep:"\n" in
  sprintf "%s\n%s" header_comment text
;;
